// Builds dist/botguard.legacy.js for bundlers that cannot read the ES module
// source: webpack 4 (HBuilderX / uni-app Vue 2) understands neither the
// "exports" field nor import.meta, and leaves private class fields to a
// parser that rejects them. The legacy file is plain ES2017 with the worker
// inlined, and package.json points "main" / "module" at it; bundlers that
// read "exports" keep using src/.
//
// Runs on prepack, so `npm pack` / `npm publish` always ship a fresh copy.
import { mkdir, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const target = 'es2017';

// The worker as a classic script: a blob URL needs no import.meta to find it.
const worker = await build({
  entryPoints: [join(root, 'src/worker.js')],
  bundle: true,
  format: 'iife',
  target,
  minify: true,
  write: false,
});
const workerSource = worker.outputFiles[0].text;

// Replaces src/spawn.js: same contract ({ worker, revoke } or null), but the
// worker runs from a same-origin blob. CSP pages need worker-src blob:,
// otherwise spawnWorker returns null and the widget solves on the main thread.
const inlineSpawn = `
const source = ${JSON.stringify(workerSource)};
export function spawnWorker() {
  try {
    const url = URL.createObjectURL(new Blob([source], { type: 'text/javascript' }));
    try {
      return { worker: new Worker(url), revoke: () => URL.revokeObjectURL(url) };
    } catch (err) {
      URL.revokeObjectURL(url);
      throw err;
    }
  } catch {
    return null;
  }
}
`;

const banner = `// @botguard/browser legacy build (ES2017, worker inlined) for webpack 4 and
// other bundlers without import.meta. Generated by scripts/build-legacy.mjs from src/.`;

const out = await build({
  entryPoints: [join(root, 'src/botguard.js')],
  bundle: true,
  format: 'esm',
  target,
  write: false,
  banner: { js: banner },
  plugins: [{
    name: 'inline-worker',
    setup(b) {
      b.onResolve({ filter: /\/spawn\.js$/ }, () => ({ path: 'spawn', namespace: 'inline-worker' }));
      b.onLoad({ filter: /.*/, namespace: 'inline-worker' }, () => ({ contents: inlineSpawn, loader: 'js' }));
    },
  }],
});
const code = out.outputFiles[0].text;
if (code.slice(banner.length).includes('import.meta')) throw new Error('legacy build still references import.meta');

const file = join(root, 'dist/botguard.legacy.js');
await mkdir(dirname(file), { recursive: true });
await writeFile(file, code);
console.log(`dist/botguard.legacy.js ${(code.length / 1024).toFixed(1)} KiB`);
